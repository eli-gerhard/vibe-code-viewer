// Embeds the built web UI (dist/web) into a TypeScript module so the server serves it from memory.
// Writes an empty asset map when the UI hasn't been built yet, so dev, tests and typecheck work.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { getMimeType } from "hono/utils/mime";
import type { EmbeddedAssets } from "../src/server/assets.ts";

const webDir = "dist/web";
const outFile = "src/server/generated/web-assets.ts";

const assets: EmbeddedAssets = {};
if (existsSync(webDir)) {
  for (const entry of readdirSync(webDir, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile()) continue;
    const file = join(entry.parentPath, entry.name);
    const urlPath = `/${relative(webDir, file).split(sep).join("/")}`;
    assets[urlPath] = {
      type: getMimeType(file) ?? "application/octet-stream",
      body: readFileSync(file).toString("base64"),
    };
  }
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/embed-web.ts. Do not edit.
import type { EmbeddedAssets } from "../assets.ts";

export const webAssets: EmbeddedAssets = ${JSON.stringify(assets, null, 2)};
`,
);
console.log(`Embedded ${Object.keys(assets).length} web files into ${outFile}`);
